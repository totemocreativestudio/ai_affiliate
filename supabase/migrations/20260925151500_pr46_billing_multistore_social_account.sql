create or replace function public.luma_admin_extend_subscription(
  p_subscription_id bigint,
  p_days integer,
  p_reason text default null
)
returns table(subscription_id bigint,user_id uuid,previous_ends_at timestamptz,new_ends_at timestamptz,status text)
language plpgsql
security invoker
set search_path=public,pg_temp
as $$
declare
  v_sub public.luma_user_subscriptions%rowtype;
  v_previous timestamptz;
  v_new timestamptz;
  v_status text;
begin
  if auth.uid() is null or not public.luma_is_admin() then
    raise exception 'Owner access required' using errcode='42501';
  end if;
  if p_days is null or p_days < 1 or p_days > 3650 then
    raise exception 'Days must be between 1 and 3650' using errcode='22023';
  end if;

  select * into v_sub
  from public.luma_user_subscriptions
  where id=p_subscription_id
  for update;

  if v_sub.id is null then
    raise exception 'Subscription not found' using errcode='P0002';
  end if;

  v_previous:=v_sub.ends_at;
  v_new:=greatest(v_sub.ends_at,now()) + make_interval(days=>p_days);
  v_status:=case when v_sub.status='trialing' then 'trialing' else 'active' end;

  update public.luma_user_subscriptions
  set ends_at=v_new,status=v_status,updated_at=now()
  where id=v_sub.id;

  insert into public.luma_subscription_adjustments(
    subscription_id,user_id,workspace_id,days_added,reason,
    previous_ends_at,new_ends_at,adjusted_by
  ) values(
    v_sub.id,v_sub.user_id,v_sub.workspace_id,p_days,nullif(trim(coalesce(p_reason,'')),''),
    v_previous,v_new,auth.uid()
  );

  return query select v_sub.id,v_sub.user_id,v_previous,v_new,v_status;
end
$$;

revoke all on function public.luma_admin_extend_subscription(bigint,integer,text) from public,anon;
grant execute on function public.luma_admin_extend_subscription(bigint,integer,text) to authenticated;

