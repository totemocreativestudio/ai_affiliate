  ) then raise exception 'Workspace access denied' using errcode='42501'; end if;

  return query
  with grouped as (
    select
      coalesce(nullif(s.sku,''),lower(coalesce(s.product_name,''))) product_key,
      max(nullif(s.sku,'')) sku,max(coalesce(nullif(s.product_name,''),pm.product_name,'')) product_name,max(s.platform) platform,
      coalesce(sum(s.qty),0) qty,coalesce(sum(s.orders),0) orders,coalesce(sum(s.gmv),0) gmv,
      coalesce(sum(s.commission),0) commission,coalesce(sum(s.clicks),0) clicks,
      coalesce(sum(s.buyers),0) buyers,coalesce(sum(s.new_buyers),0) new_buyers,
      coalesce(sum(s.refund),0) refund,coalesce(sum(s.refund_qty),0) refund_qty,
      case when coalesce(sum(s.commission),0)>0 then round(sum(s.gmv)/sum(s.commission),2) else coalesce(max(s.roi),0) end roi
    from public.sales s
    left join public.product_master pm on pm.workspace_id=s.workspace_id and pm.sku_normalized=lower(coalesce(s.sku,''))
    where s.workspace_id=p_workspace_id and s.data_type='product_performance'
      and (p_start_date is null or s.data_date>=p_start_date)
      and (p_end_date is null or s.data_date<=p_end_date)
      and (p_platform is null or p_platform='' or lower(s.platform)=lower(p_platform))
      and (p_store_name is null or p_store_name='' or lower(coalesce(s.store_name,''))=lower(p_store_name))
    group by coalesce(nullif(s.sku,''),lower(coalesce(s.product_name,'')))
  ),
  filtered as (
    select g.* from grouped g
    where p_search is null or p_search=''
       or coalesce(g.sku,'') ilike '%'||p_search||'%'
       or coalesce(g.product_name,'') ilike '%'||p_search||'%'
  ),
  numbered as (
    select row_number() over(order by f.gmv desc,f.orders desc,f.qty desc,f.product_key asc) row_rank,f.* from filtered f
  )
  select n.row_rank,n.sku,n.product_name,n.platform,n.qty,n.orders,n.gmv,n.commission,n.clicks,n.buyers,n.new_buyers,
         n.refund,n.refund_qty,n.roi,count(*) over()
  from numbered n
  order by n.row_rank
  limit greatest(1,least(coalesce(p_page_size,50),100))
  offset greatest(0,coalesce(p_page,1)-1)*greatest(1,least(coalesce(p_page_size,50),100));
end
$$;

create or replace function public.get_store_dashboard_v2(
  p_workspace_id uuid,
  p_start_date date default null,
  p_end_date date default null,
  p_platform text default null,
  p_store_name text default null
)
returns table(store_name text,platform text,total_affiliates bigint,active_affiliates bigint,inactive_affiliates bigint,gmv numeric,orders numeric,qty numeric,spend numeric,roi numeric)
language plpgsql
security definer
set search_path=public,pg_temp
as $$
begin
  if auth.uid() is null then raise exception 'Authentication required' using errcode='42501'; end if;
  if not (
    public.luma_is_admin()
    or exists(select 1 from public.workspace_members wm where wm.workspace_id=p_workspace_id and wm.user_id=auth.uid())
  ) then raise exception 'Workspace access denied' using errcode='42501'; end if;

  return query
  with stores as (
    select coalesce(nullif(s.store_name,''),'Unassigned') store_name,max(s.platform) platform,
           count(distinct s.creator_id)::bigint total_affiliates,
           count(distinct s.creator_id) filter(where coalesce(s.gmv,0)<>0 or coalesce(s.orders,0)<>0 or coalesce(s.qty,0)<>0)::bigint active_affiliates,
           coalesce(sum(s.gmv),0) gmv,coalesce(sum(s.orders),0) orders,coalesce(sum(s.qty),0) qty,
           coalesce(sum(coalesce(s.cost_product,0)+coalesce(s.shipping_cost,0)+coalesce(s.ads_spend,0)),0) spend
    from public.sales s
    where s.workspace_id=p_workspace_id
      and s.data_type in ('performance','sales')
      and nullif(trim(s.store_name),'') is not null
      and (p_start_date is null or s.data_date>=p_start_date)
      and (p_end_date is null or s.data_date<=p_end_date)
      and (p_platform is null or p_platform='' or lower(s.platform)=lower(p_platform))
      and (p_store_name is null or p_store_name='' or lower(s.store_name)=lower(p_store_name))
    group by s.store_name
  )
  select s.store_name,s.platform,s.total_affiliates,s.active_affiliates,
         greatest(0,s.total_affiliates-s.active_affiliates)::bigint,s.gmv,s.orders,s.qty,s.spend,
         case when s.spend>0 then round(s.gmv/s.spend,2) else 0 end
  from stores s
  order by s.gmv desc,s.store_name;
end
$$;

