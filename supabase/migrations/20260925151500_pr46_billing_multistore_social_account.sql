  p_workspace_id uuid,
  p_platform text default null,
  p_store_name text default null
)
returns date
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare v_date date;
begin
  if auth.uid() is null then raise exception 'Authentication required' using errcode='42501'; end if;
