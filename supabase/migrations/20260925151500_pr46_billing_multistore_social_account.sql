create or replace function public.luma_owner_verified_revenue(p_year integer)
returns table(
  month_number integer,
  subscription_revenue numeric,
  token_revenue numeric,
  total_revenue numeric
)
language plpgsql
security invoker
set search_path=public,pg_temp
as $$
begin
  if auth.uid() is null or not public.luma_is_admin() then
    raise exception 'Owner access required' using errcode='42501';
  end if;
  if p_year < 2020 or p_year > 2100 then
    raise exception 'Invalid year' using errcode='22023';
  end if;

  return query
  with months as (
    select generate_series(1,12)::integer month_number
  ),
  subscription_paid as (
    select extract(month from paid_at)::integer month_number,
           coalesce(sum(amount),0)::numeric revenue
    from public.luma_subscription_orders
    where status='paid'
      and paid_at >= make_date(p_year,1,1)
      and paid_at < make_date(p_year+1,1,1)
    group by 1
  ),
  token_paid as (
    select extract(month from paid_at)::integer month_number,
           coalesce(sum(amount),0)::numeric revenue
    from public.luma_topup_orders
    where status='paid'
      and paid_at >= make_date(p_year,1,1)
      and paid_at < make_date(p_year+1,1,1)
    group by 1
  )
  select m.month_number,
         coalesce(s.revenue,0)::numeric,
         coalesce(t.revenue,0)::numeric,
         (coalesce(s.revenue,0)+coalesce(t.revenue,0))::numeric
  from months m
  left join subscription_paid s using(month_number)
  left join token_paid t using(month_number)
  order by m.month_number;
end
$$;

revoke all on function public.luma_owner_verified_revenue(integer) from public,anon;
grant execute on function public.luma_owner_verified_revenue(integer) to authenticated,service_role;

